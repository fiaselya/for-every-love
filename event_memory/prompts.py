"""事件记忆系统的 prompt 模板：分段 / 关键词与摘要 / 相关性判断。

三个模板均为含占位符的字符串。提取器用 `.replace()` 把运行时数据填进去，
避免 LLM 返回内容里的 `{` `}` 破坏 `str.format` 格式化。
"""

from __future__ import annotations


# ---- 分段：把对话历史切出语义完整的已完成事件 ----

SEGMENT_PROMPT = """\
你是一个对话分段助手。根据历史对话，切分出语义完整的"已完成事件"。

历史对话（每行为"角色: 内容"）：
__HISTORY__

输出要求：
- 只严格输出 JSON，schema 为：
{"events": [{"text": 事件原文, "status": "completed"}]}
- 事件原文(text) 是该事件的输入与输出原文拼接，不含任何思考过程。
- 只切语义完整、已经写完/做完的事件；正在进行的当前任务不要切。
- 若没有任何符合的已完成事件，返回 {"events": []}。
"""


# ---- 提取：从事件原文抽关键词与一句话摘要 ----

EXTRACT_PROMPT = """\
你是一个事件关键词与摘要提取助手。根据事件原文，提取关键词与一句话摘要。

事件原文：
__EVENT__

输出要求：
- 只严格输出 JSON，schema 为：
{"hard": [...], "soft": [...], "summary": "..."}
- hard：硬关键词，最多 5 个，只准用原文字面出现的短语，禁止同义改写。
- soft：软关键词，最多 8 个，表示主题/意图/动作。
- summary：一句话摘要。
- 若无合适的关键词，相应数组返回空数组。
"""


# ---- 判断：从候选里挑出与 query 相关的事件 ----

JUDGE_PROMPT = """\
你是一个相关性判断助手。根据用户 query，从候选事件里挑出真正相关的，宁缺勿滥。

用户 query：
__QUERY__

候选事件列表（每项含 event_id、summary、date）：
__CANDIDATES__

输出要求：
- 只严格输出 JSON，schema 为：
{"relevant": [相关的 event_id]}
- 只挑确实相关的；没有相关的就返回空数组。
"""
